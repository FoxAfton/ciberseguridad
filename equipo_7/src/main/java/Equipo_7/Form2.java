    private void Email_txtKeyTyped(java.awt.event.KeyEvent evt) {//GEN-FIRST:event_Email_txtKeyTyped
        // TODO add your handling code here:
        char c = evt.getKeyChar();
        String Texto = Email_txt.getText();
        if (Character.isUpperCase(c)) {
            evt.setKeyChar(Character.toLowerCase(c));
            c = Character.toLowerCase(c);
        }

        if (c == ' ') {
            evt.consume();
            return;
        }

        if (c == '@' && Texto.contains("@")) {
            evt.consume();
            return;
        }

        if (!String.valueOf(c).matches("[a-z0-9@._-]")) {
            evt.consume();
        }
    }//GEN-LAST:event_Email_txtKeyTyped

    private void Email_txtFocusLost(java.awt.event.FocusEvent evt) {//GEN-FIRST:event_Email_txtFocusLost
        // TODO add your handling code here:
        String email = Email_txt.getText();

        String patron = "^[a-z0-9._-]+@[a-z0-9.-]+\\.[a-z]{2,6}$";

        if (!email.matches(patron)) {
            Email_txt.setBackground(new java.awt.Color(255, 200, 200));
        } else {
            Email_txt.setBackground(java.awt.Color.WHITE);
        }
    }//GEN-LAST:event_Email_txtFocusLost

