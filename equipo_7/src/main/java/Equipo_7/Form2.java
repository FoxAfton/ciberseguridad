    private void Btn_BuscarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_Btn_BuscarActionPerformed
        // TODO add your handling code here:
    String idTexto = JOptionPane.showInputDialog("insertar el ID para buscar:");
    Logica_De_Negocio logica = new Logica_De_Negocio();
    Trabajador t = logica.BuscarTrabajador(idTexto);
    
    if (t != null) {
        // Llenar los campos con los datos encontrados
        Nombre_txt.setText(t.getNombre());
        Email_txt.setText(t.getEmail());
        RFC_txt.setText(t.getRFC());
        Fecha_Alta_txt.setText(t.getFechadeAlta());
        Seguro_Social_txt.setText(t.getSeguroSocial());
        Departamento_Combo.setSelectedItem(t.getDepartamento());
        SueldoB_txt.setText(String.valueOf(t.getSueldo()));
        AltaIMSS_txt.setText(t.getAltaImss());
    } else {
        JOptionPane.showMessageDialog(this, 
            "no se encontro ningun trabajador con el ID: " + idTexto,
            "no encontrado", 
            JOptionPane.WARNING_MESSAGE);
    }
    }//GEN-LAST:event_Btn_BuscarActionPerformed

